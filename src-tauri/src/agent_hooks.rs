#[tauri::command]
pub(crate) fn setup_agent_hooks(agent: String) -> Result<AgentHooksSetupResult, String> {
    setup_agent_hooks_impl(parse_agent(&agent)?)
}

pub fn setup_agent_hooks_impl(agent: AgentKind) -> Result<AgentHooksSetupResult, String> {
    let store_path = resume_store_path()?;
    match agent {
        AgentKind::Claude => {
            let home = home_dir().ok_or_else(|| "neither USERPROFILE nor HOME is available".to_owned())?;
            let script_path = home.join(".claude").join("hooks").join("tonymux-save-resume.ps1");
            let settings_path = home.join(".claude").join("settings.json");
            write_hook_script(&script_path, agent, &store_path)?;
            merge_claude_settings(&settings_path, &script_path)?;
            Ok(AgentHooksSetupResult {
                agent,
                script_path: script_path.display().to_string(),
                config_path: settings_path.display().to_string(),
                message: "Claude Code hooks installed: Stop + SessionEnd save the resume command on every turn and at session end.".to_owned(),
            })
        }
        AgentKind::Codex => {
            let home = home_dir().ok_or_else(|| "neither USERPROFILE nor HOME is available".to_owned())?;
            let script_path = home.join(".codex").join("hooks").join("tonymux-save-resume.ps1");
            let hooks_path = home.join(".codex").join("hooks.json");
            write_hook_script(&script_path, agent, &store_path)?;
            merge_codex_hooks(&hooks_path, &script_path)?;
            Ok(AgentHooksSetupResult {
                agent,
                script_path: script_path.display().to_string(),
                config_path: hooks_path.display().to_string(),
                message: "Codex hooks installed: SessionEnd writes the resume command within the 3s teardown budget.".to_owned(),
            })
        }
        AgentKind::Opencode => {
            let config_dir = opencode_config_dir()?;
            let plugin_path = config_dir.join("plugins").join("tonymux-resume.js");
            write_opencode_plugin(&plugin_path, &store_path)?;
            Ok(AgentHooksSetupResult {
                agent,
                script_path: plugin_path.display().to_string(),
                config_path: config_dir.display().to_string(),
                message: "opencode plugin installed in the global plugins directory; session.idle events write the resume command.".to_owned(),
            })
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn powershell_script_embeds_store_path_and_flags() {
        let store = PathBuf::from("C:\\Users\\me\\AppData\\Local\\tonymux\\resume\\resume.jsonl");
        let script = render_powershell_script(AgentKind::Claude, &store, "--resume", "--cwd");
        assert!(script.contains("agent = \"claude\""));
        assert!(script.contains("C:\\Users\\me\\AppData\\Local\\tonymux\\resume\\resume.jsonl"));
        assert!(script.contains("\"--resume\", [string]$payload.session_id, \"--cwd\""));
    }

    #[test]
    fn codex_script_uses_resume_and_cd_flags() {
        let store = PathBuf::from("/tmp/resume.jsonl");
        let script = render_powershell_script(AgentKind::Codex, &store, "resume", "--cd");
        assert!(script.contains("args = @(\"resume\", [string]$payload.session_id, \"--cd\""));
    }

    #[test]
    fn merge_preserves_existing_keys_and_events() {
        let mut root = json!({
            "permissions": { "allow": ["Bash(npm run build)"] },
            "hooks": { "PreToolUse": [{ "hooks": [{ "type": "command", "command": "echo hi" }] }] }
        });
        merge_hook_entry(
            &mut root,
            "SessionEnd",
            json!({ "hooks": [{ "type": "command", "command": "powershell.exe -File x.ps1", "timeout": 10 }] }),
        );
        assert_eq!(root["permissions"]["allow"][0], "Bash(npm run build)");
        assert_eq!(root["hooks"]["PreToolUse"].as_array().unwrap().len(), 1);
        assert_eq!(root["hooks"]["SessionEnd"].as_array().unwrap().len(), 1);
        assert_eq!(root["hooks"]["SessionEnd"][0]["hooks"][0]["timeout"], 10);
    }

    #[test]
    fn merge_is_idempotent() {
        let mut root = json!({});
        let entry = json!({ "hooks": [{ "type": "command", "command": "powershell.exe -File x.ps1", "timeout": 10 }] });
        merge_hook_entry(&mut root, "SessionEnd", entry.clone());
        merge_hook_entry(&mut root, "SessionEnd", entry.clone());
        assert_eq!(root["hooks"]["SessionEnd"].as_array().unwrap().len(), 1);
    }

    #[test]
    fn merge_creates_hooks_object_when_missing() {
        let mut root = json!({ "model": "claude-sonnet-4" });
        merge_hook_entry(
            &mut root,
            "Stop",
            json!({ "hooks": [{ "type": "command", "command": "powershell.exe -File y.ps1" }] }),
        );
        assert!(root["hooks"]["Stop"].is_array());
        assert_eq!(root["model"], "claude-sonnet-4");
    }

    #[test]
    fn opencode_plugin_embeds_store_path() {
        let store = PathBuf::from("C:\\Users\\me\\AppData\\Local\\tonymux\\resume\\resume.jsonl");
        let plugin = OPENCODE_PLUGIN_TEMPLATE.replace("__STORE_PATH__", &store.display().to_string());
        assert!(plugin.contains("C:\\Users\\me\\AppData\\Local\\tonymux\\resume\\resume.jsonl"));
        assert!(plugin.contains("session.status"));
        assert!(plugin.contains("\"opencode\""));
    }

    #[test]
    fn script_write_round_trip() {
        let dir = env::temp_dir().join(format!("agent-hooks-test-{}", std::process::id()));
        let script = dir.join("hooks").join("tonymux-save-resume.ps1");
        write_hook_script(&script, AgentKind::Claude, &dir.join("resume.jsonl")).unwrap();
        let content = fs::read_to_string(&script).unwrap();
        assert!(content.contains("# TonyMux resume saver (claude)"));
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn setup_claude_writes_script_and_merges_settings() {
        let dir = env::temp_dir().join(format!("agent-hooks-setup-{}", std::process::id()));
        let script = dir.join("hooks").join("tonymux-save-resume.ps1");
        let settings = dir.join("settings.json");
        write_hook_script(&script, AgentKind::Claude, &dir.join("resume.jsonl")).unwrap();
        fs::write(&settings, r#"{ "permissions": { "allow": ["Bash(npm test)"] } }"#).unwrap();
        merge_claude_settings(&settings, &script).unwrap();
        let root: Value = serde_json::from_str(&fs::read_to_string(&settings).unwrap()).unwrap();
        assert_eq!(root["permissions"]["allow"][0], "Bash(npm test)");
        assert_eq!(root["hooks"]["Stop"].as_array().unwrap().len(), 1);
        assert_eq!(root["hooks"]["SessionEnd"].as_array().unwrap().len(), 1);
        assert_eq!(root["hooks"]["SessionEnd"][0]["hooks"][0]["timeout"], 10);
        let _ = fs::remove_dir_all(&dir);
    }
}
